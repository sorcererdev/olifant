{-# OPTIONS_GHC -Wno-incomplete-uni-patterns #-}
module Olifant.RegionSpec (spec) where

import Data.Map.Strict qualified as M
import Data.Text (Text)
import Data.Text qualified as T
import Olifant.Query (Query (..))
import Olifant.Region
import Olifant.Template (Value (..), parseTemplate)
import Test.Hspec

cabalRegion :: RegionDef
cabalRegion = RegionDef "library-modules" "olifant.cabal" (GlobQuery "src/**/*.hs" []) (ItemTemplate t) False Nothing Nothing Nothing
  where Right t = parseTemplate "{= dotted =}"

records :: [M.Map Text Value]
records = [M.fromList [("dotted", VText d)] | d <- ["Olifant.B", "Olifant.A", "Olifant.B"]]

cabal :: Text
cabal = T.unlines
  [ "library", "  exposed-modules:"
  , "    -- olifant:region library-modules (old header text)", "    Olifant.Stale", "    -- olifant:end library-modules"
  , "", "test-suite spec" ]

spec :: Spec
spec = do
  describe "renderRegion" $
    it "renders one line per record, sorted and deduplicated" $
      renderRegion cabalRegion records `shouldBe` Right ["Olifant.A", "Olifant.B"]
  describe "applyRegion" $ do
    it "replaces the block between the fences, at the fence's indentation, refreshing the header" $
      applyRegion cabalRegion "--" ["Olifant.A", "Olifant.B"] cabal
        `shouldBe` Right (T.unlines
          [ "library", "  exposed-modules:"
          , "    -- olifant:region library-modules (generated from glob src/**/*.hs; edit the declaration, not this block)"
          , "    Olifant.A", "    Olifant.B", "    -- olifant:end library-modules"
          , "", "test-suite spec" ])
    it "is the identity when the block is already right" $ do
      let Right once = applyRegion cabalRegion "--" ["Olifant.A"] cabal
      applyRegion cabalRegion "--" ["Olifant.A"] once `shouldBe` Right once
    it "keeps CRLF line endings (Review Focus 3)" $
      fmap ("\r\n" `T.isInfixOf`) (applyRegion cabalRegion "--" ["Olifant.A"] (T.replace "\n" "\r\n" cabal)) `shouldBe` Right True
    it "reports missing fences as FenceMissing, and broken ones as FenceBroken" $ do
      applyRegion cabalRegion "--" [] "library\n" `shouldBe` Left FenceMissing
      applyRegion cabalRegion "--" [] "-- olifant:region library-modules\n" `shouldSatisfy` either isBroken (const False)
      applyRegion cabalRegion "--" [] "-- olifant:end library-modules\n-- olifant:region library-modules\n" `shouldSatisfy` either isBroken (const False)
    it "does not confuse a region with another whose name it prefixes" $
      applyRegion cabalRegion "--" [] "-- olifant:region library-modules-extra\n-- olifant:end library-modules-extra\n" `shouldBe` Left FenceMissing
    it "writes a whole file with a header" $ do
      let whole = cabalRegion {regionWholeFile = True}
      applyRegion whole "--" ["A", "B"] "anything" `shouldBe` Right "-- Generated by olifant (region library-modules, from glob src/**/*.hs); edit the declaration, not this file.\nA\nB\n"
  describe "parseRegions" $ do
    it "reads item and whole-file regions" $ do
      let src = T.unlines
            [ "[regions.library-modules]", "file = \"olifant.cabal\"", "query = { glob = \"src/**/*.hs\", exclude = [\"**/*Spec.hs\"] }", "item = \"{= dotted =}\"", "init_at = \"after first line matching ^  exposed-modules:\""
            , "[regions.pages]", "file = \"src/Pages.elm\"", "whole_file = true", "query = { glob = \"src/Page/*.elm\" }", "template = \"pages.elm.dt\"" ]
      fmap (map (\r -> (regionName r, regionFile r, regionWholeFile r))) (parseRegions src)
        `shouldBe` Right [("library-modules", "olifant.cabal", False), ("pages", "src/Pages.elm", True)]
    it "needs exactly one of item or template" $
      parseRegions "[regions.x]\nfile = \"a\"\nquery = { glob = \"*\" }\n" `shouldSatisfy` either ("`item` or `template`" `T.isInfixOf`) (const False)
  where
    isBroken = \case FenceBroken _ -> True; _ -> False
