-- | Owned regions (spec §5.8): blocks Olifant rewrites in full from a query,
-- between fences or as a whole file. Everything here is pure.
module Olifant.Region
  ( RegionBody (..)
  , RegionDefWith (..)
  , RegionDef
  , RegionProblem (..)
  , parseRegions
  , renderRegion
  , applyRegion
  , fenceLines
  , describeRegionProblem
  ) where

import Data.Bifunctor (first)
import Data.List (nub, sort)
import Data.Map.Strict qualified as M
import Data.Maybe (fromMaybe)
import Data.Text (Text)
import Data.Text qualified as T
import Olifant.Query (Query, Record, describeQuery, queryFromTree)
import Olifant.Template (Template, TemplateError, Value (..), describeTemplateError, parseTemplate, render)
import Olifant.Toml

data RegionBody src = ItemTemplate Template | WholeTemplate src
  deriving stock (Show, Functor, Foldable, Traversable)

data RegionDefWith src = RegionDef
  { regionName :: Text
  , regionFile :: FilePath
  , regionQuery :: Query
  , regionBody :: RegionBody src
  , regionWholeFile :: Bool
  , regionComment :: Maybe Text
  , regionInitAt :: Maybe Text
  }
  deriving stock (Show, Functor, Foldable, Traversable)

type RegionDef = RegionDefWith Template

data RegionProblem = FenceMissing | FenceBroken Text
  deriving stock (Eq, Show)

parseRegions :: Text -> Either Text [RegionDefWith FilePath]
parseRegions src = do
  top <- parseToml src
  onlyKeys ["regions"] top
  regions <- maybe M.empty id <$> optional "regions" table top
  traverse (\(name, v) -> inKey ("regions." <> name) (table v >>= region name)) (M.toList regions)
  where
    region name t = do
      onlyKeys ["file", "query", "item", "template", "whole_file", "comment", "init_at"] t
      file <- T.unpack <$> required "file" text t
      q <- required "query" queryFromTree t
      body <- case (M.lookup "item" t, M.lookup "template" t) of
        (Just v, Nothing) -> inKey "item" (text v >>= first describeTemplateError . parseTemplate) >>= pure . ItemTemplate
        (Nothing, Just v) -> WholeTemplate . T.unpack <$> inKey "template" (text v)
        _ -> Left "a region needs exactly one of `item` or `template`"
      whole <- fromMaybe False <$> optional "whole_file" bool t
      comment <- optional "comment" text t
      initAt <- optional "init_at" text t
      pure (RegionDef name file q body whole comment initAt)

renderRegion :: RegionDef -> [Record] -> Either TemplateError [Text]
renderRegion def records = case regionBody def of
  ItemTemplate t -> sort . nub . filter (not . T.null) . map T.strip <$> traverse (\r -> render r t) records
  WholeTemplate t -> T.lines <$> render (M.fromList [("items", VList (map VRecord records))]) t

fenceLines :: RegionDef -> Text -> (Text, Text)
fenceLines def c =
  ( c <> " olifant:region " <> regionName def <> " (generated from " <> describeQuery (regionQuery def) <> "; edit the declaration, not this block)"
  , c <> " olifant:end " <> regionName def
  )

applyRegion :: RegionDef -> Text -> [Text] -> Text -> Either RegionProblem Text
applyRegion def c body content
  | regionWholeFile def =
      Right (T.unlines ((c <> " Generated by olifant (region " <> regionName def <> ", from " <> describeQuery (regionQuery def) <> "); edit the declaration, not this file.") : body))
  | otherwise =
      case (hits openTag, hits closeTag) of
        ([], []) -> Left FenceMissing
        ([o], [e])
          | o < e ->
              let indent = T.takeWhile (\ch -> ch == ' ' || ch == '\t') (ls !! o)
                  (open, close) = fenceLines def c
                  new = take o ls ++ [indent <> open] ++ map (indentLine indent) body ++ [indent <> close] ++ drop (e + 1) ls
               in Right (T.intercalate newline new)
          | otherwise -> Left (FenceBroken "its end comes before its start")
        (os, es)
          | length os > 1 || length es > 1 -> Left (FenceBroken "it appears more than once")
          | null es -> Left (FenceBroken ("it has no end (`" <> closeTag <> "`)"))
          | otherwise -> Left (FenceBroken ("it has an end but no start (`" <> openTag <> "`)"))
  where
    newline = if "\r\n" `T.isInfixOf` content then "\r\n" else "\n"
    ls = T.splitOn newline content
    openTag = c <> " olifant:region " <> regionName def
    closeTag = c <> " olifant:end " <> regionName def
    hits tag = [i | (i, l) <- zip [0 ..] ls, let s = T.strip l, s == tag || (tag <> " ") `T.isPrefixOf` s]
    indentLine indent l = if T.null l then l else indent <> l

describeRegionProblem :: RegionDef -> RegionProblem -> Text
describeRegionProblem def = \case
  FenceMissing -> "region `" <> regionName def <> "` has no fences in " <> T.pack (regionFile def) <> " (run `olifant sync --init " <> regionName def <> "`)"
  FenceBroken why -> "region `" <> regionName def <> "` in " <> T.pack (regionFile def) <> " is broken: " <> why
